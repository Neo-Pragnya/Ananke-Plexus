# ---------------------------------------------------------------------------------------------- conformance
def test_protocol_and_discovery(provider: CapabilityProvider) -> None:
    assert isinstance(provider, CapabilityProvider)
    first = provider.discover("", None, 1)
    assert len(first.items) == 1 and first.cursor == "1"
    rest = provider.discover("", first.cursor, 10)
    assert rest.cursor is None and {d.name for d in first.items + rest.items} >= {"graph-review"}
    assert [d.name for d in provider.discover("graph").items] == ["graph-review"]


def test_resolve_is_exact_and_errors_are_coded(provider: CapabilityProvider) -> None:
    d = provider.resolve(CapabilityRef.parse("graph-review"))
    assert d.identity == f"{provider.source_id}:{d.namespace}/graph-review" and len(d.digest) == 64
    assert (
        provider.resolve(CapabilityRef.parse(f"{d.namespace}/graph-review@sha256:{d.digest}")) == d
    )
    with pytest.raises(SourceError) as missing:
        provider.resolve(CapabilityRef.parse("nope"))
    assert missing.value.code == "NOT_FOUND"
    with pytest.raises(SourceError) as wrong:
        provider.resolve(CapabilityRef.parse("graph-review@9.9.9"))
    assert wrong.value.code == "VERSION_NOT_FOUND"


def test_fetch_verifies_digest_and_publish_is_refused(provider: CapabilityProvider) -> None:
    d = provider.resolve(CapabilityRef.parse("graph-review"))
    got = provider.fetch(d)
    assert digest_files(got.files) == d.digest and "SKILL.md" in got.files
    with pytest.raises(SourceError) as ro:
        provider.publish(Path("."), approved_by="someone")
    assert ro.value.code == "READ_ONLY"


