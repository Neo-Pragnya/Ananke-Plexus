def test_unknown_metadata_is_explicit_and_bytes_preserved(local: LocalDirectoryProvider) -> None:
    notes = local.resolve(CapabilityRef.parse("notes"))
    assert notes.version == "unknown" and set(notes.unknown) == {"version", "license"}
    gr = local.resolve(CapabilityRef.parse("team/graph-review@1.2.0"))
